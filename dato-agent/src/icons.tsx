import type { SVGProps } from 'react';

// Font Awesome 7 Free glyphs (solid, CC BY 4.0 License). Like every icon
// that a component of datocms-react-ui takes, each one is an svg that takes
// the props of an svg. Like the icons of the CMS, it is 1em of the text: a
// button or a pill shows it at that size, and a place with a size of its own
// (a blank slate) sets it in CSS, which wins over the attributes.

type IconProps = SVGProps<SVGSVGElement>;

type GlyphProps = IconProps & {
  /** The width of the glyph's box; every glyph is 512 high */
  boxWidth: number;
  d: string;
};

function Glyph({ boxWidth, d, style, ...props }: GlyphProps) {
  return (
    <svg
      viewBox={`0 0 ${boxWidth} 512`}
      width="1em"
      height="1em"
      fill="currentColor"
      aria-hidden="true"
      {...props}
      // Some glyphs draw a little past their box, as in Font Awesome: the
      // box must not clip them.
      style={{ overflow: 'visible', ...style }}
    >
      <path d={d} />
    </svg>
  );
}

